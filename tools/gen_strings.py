PH = re.compile(r"%\d+\$[sd]")

def esc(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if s[:1] in ("@", "?"):
        s = "\\" + s
    return s

def main():
    base = T["en"]
    errores = []
    for lang, d in T.items():
        faltan = set(base) - set(d)
        sobran = set(d) - set(base)
        if faltan: errores.append(f"{lang}: faltan {sorted(faltan)}")
        if sobran: errores.append(f"{lang}: sobran {sorted(sobran)}")
        for k, v in d.items():
            if k in base and sorted(PH.findall(v)) != sorted(PH.findall(base[k])):
                errores.append(f"{lang}.{k}: marcadores {PH.findall(v)} != {PH.findall(base[k])}")
    if errores:
        print("\n".join(errores)); sys.exit(1)

    for lang, d in T.items():
        carpeta = os.path.join(RES, FOLDER[lang])
        os.makedirs(carpeta, exist_ok=True)
        lineas = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
        if lang == "en":
            lineas.append('    <string name="app_name" translatable="false">OpenCallShield</string>')
            lineas.append('    <string name="msg_raw" translatable="false">%1$s</string>')
        for k in base:  # mismo orden en todos los idiomas
            lineas.append(f'    <string name="{k}">{esc(d[k])}</string>')
        lineas.append("</resources>")
        with open(os.path.join(carpeta, "strings.xml"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lineas) + "\n")
        print(f"OK {FOLDER[lang]:10s} {len(d)} textos")

main()
